// 把解法字符串拆成操作序列：'|' 记作 'rewind'
export function solutionActions(solution) {
  return [...solution].map((ch) => {
    if (ch === '|') return 'rewind';
    if ('UDLRW'.includes(ch)) return ch;
    throw new Error('解法里有未知字符: ' + ch);
  });
}

// 把解法字符串应用到一局游戏上（测试、演示用）
export function applySolution(game, solution) {
  for (const a of solutionActions(solution)) {
    if (a === 'rewind') game.rewind();
    else game.step(a);
  }
  return game.won;
}
